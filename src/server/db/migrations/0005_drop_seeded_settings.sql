/* ردیف‌هایی که اسکریپت seed از پیش‌فرض‌های کد در `settings` نوشته بود پاک
   می‌شوند تا سایت دوباره پیش‌فرض فعلی کد را بخواند.

   آن ردیف‌ها پیش‌فرض را منجمد کرده بودند: منوی بازطراحی‌شده و لوگوی تازهٔ
   SUNWAYS هرگز روی سایت نمی‌نشستند، چون نسخهٔ قدیمیِ ذخیره‌شده بر پیش‌فرض
   تازه غلبه می‌کرد — و برای آرایه‌ها ادغام یعنی جایگزینی کامل، نه ترکیب.

   فقط کلیدهایی که seed می‌نوشت، و فقط وقتی نویسنده ثبت نشده: ذخیره از پنل
   همیشه `updated_by` را پر می‌کند، پس هر چیزی که ویراستاری عوض کرده
   دست‌نخورده می‌ماند. اسکریپت seed هم دیگر این ردیف‌ها را نمی‌نویسد. */
DELETE FROM `settings`
WHERE `updated_by` IS NULL
  AND `key` IN ('site', 'nav', 'stats', 'brands', 'clients', 'portfolio', 'areas',
                'timeline', 'capabilities', 'heroSlides', 'promoSlides');
